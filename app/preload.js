// Bridge between the window and the main process: only these functions are available.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('partsfinder', {
  config: () => ipcRenderer.invoke('config'),
  who: () => ipcRenderer.invoke('who'),
  signIn: (key, remember) => ipcRenderer.invoke('sign-in', key, remember),
  signOut: () => ipcRenderer.invoke('sign-out'),
  login: (username, password, remember) => ipcRenderer.invoke('login', username, password, remember),
  setup: (username, password, remember) => ipcRenderer.invoke('setup', username, password, remember),
  authInfo: () => ipcRenderer.invoke('auth-info'),
  users: () => ipcRenderer.invoke('users'),
  userCreate: (body) => ipcRenderer.invoke('user-create', body),
  userUpdate: (username, body) => ipcRenderer.invoke('user-update', username, body),
  userDelete: (username) => ipcRenderer.invoke('user-delete', username),
  companyConfidential: (companyId, on) => ipcRenderer.invoke('company-confidential', companyId, on),
  companyCreate: (body) => ipcRenderer.invoke('company-create', body),
  companyDelete: (companyId) => ipcRenderer.invoke('company-delete', companyId),
  folderAccess: (companyId, name, folderPath, access) => ipcRenderer.invoke('folder-access', companyId, name, folderPath, access),
  library: (companyId) => ipcRenderer.invoke('library', companyId),
  uploadFolder: (companyId, existingName, access) => ipcRenderer.invoke('upload-folder', companyId, existingName, access),
  removeFolder: (companyId, name) => ipcRenderer.invoke('remove-folder', companyId, name),
  onUploadProgress: (cb) => ipcRenderer.on('upload-progress', (_e, p) => cb(p)),
  health: () => ipcRenderer.invoke('health'),
  appInfo: () => ipcRenderer.invoke('app-info'),
  aiSettings: () => ipcRenderer.invoke('ai-settings'),
  setAiKey: (key) => ipcRenderer.invoke('ai-key-set', key),
  companies: () => ipcRenderer.invoke('companies'),
  search: (body) => ipcRenderer.invoke('search', body),
  part: (id, companyId) => ipcRenderer.invoke('part', id, companyId),
  quality: (companyId) => ipcRenderer.invoke('quality', companyId),
  duplicates: (companyId, limit) => ipcRenderer.invoke('duplicates', companyId, limit),
  filters: (companyId, category) => ipcRenderer.invoke('filters', companyId, category),
  searchShape: (bytes, filename, companyId) => ipcRenderer.invoke('search-shape', bytes, filename, companyId),
  feedback: (body) => ipcRenderer.invoke('feedback', body),
  similar: (id, companyId) => ipcRenderer.invoke('similar', id, companyId),
  saveFile: (url, name) => ipcRenderer.invoke('save-file', url, name),
  searchImage: (body) => ipcRenderer.invoke('search-image', body),
  mesh: (url) => ipcRenderer.invoke('mesh', url),
  openDatasheet: (url, title) => ipcRenderer.invoke('open-datasheet', url, title),
  pickAndIngest: (companyId) => ipcRenderer.invoke('pick-and-ingest', companyId),
  onBackendState: (cb) => ipcRenderer.on('backend-state', (_e, s) => cb(s)),
  onIngestProgress: (cb) => ipcRenderer.on('ingest-progress', (_e, p) => cb(p)),
  onIngestStarted: (cb) => ipcRenderer.on('ingest-started', (_e, folder) => cb(folder)),
});
