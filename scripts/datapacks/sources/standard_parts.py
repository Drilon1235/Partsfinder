def _bore_code(d: float) -> str:
    return {10: "00", 12: "01", 15: "02", 17: "03"}.get(int(d), f"{int(d) // 5:02d}")


def bearing_designation(d: float, big: float, w: float) -> tuple[str, str] | None:
    """(series, designation) of a deep groove bearing of these dimensions, or None."""
    key = (round(d), round(big), round(w))
    if key in _MINIATURE and abs(d - key[0]) < .01:
        return "6", _MINIATURE[key]
    for series, sizes in _SERIES.items():
        if key in sizes and abs(w - key[2]) < .01:
            return series, f"{series}{_bore_code(d)}"
    return None


def with_designation(meta: dict) -> dict:
    """Adds the ISO designation (6205, 6205-2RS, 7205 B, NU 205) to bearings it can name."""
    p = meta.get("properties", {})
    if "bearing" not in meta.get("category_path", "") or not {"inner_diameter_mm", "outer_diameter_mm", "width_mm"} <= set(p):
        return meta
    found = bearing_designation(p["inner_diameter_mm"], p["outer_diameter_mm"], p["width_mm"])
    if not found:
        return meta
    series, deep = found
    kind = p.get("type")
    code = {"open": deep, "sealed": f"{deep}-2RS"}.get(kind)
    if kind == "angular-contact" and series in ("62", "63"):
        code = f"7{deep[1:]} B"
    if kind == "cylindrical-roller" and series in ("62", "63"):
        code = f"NU {deep[1:]}"
    if not code:
        return meta
    meta = {**meta, "properties": {**p, "designation": code}}
    meta["name"] = f"{meta['name']} ({code})"
    meta["description"] = f"{meta['description']} Designation {code} (ISO 15)."
    meta["tags"] = list(dict.fromkeys([*meta.get("tags", []), code.lower(), code.replace(' ', '').lower()]))
    return meta


def items(src: Path) -> list[Item]:
    out: list[Item] = []
    for meta_file in sorted(src.rglob("*.json")):
        step = meta_file.with_suffix(".step")
        if not step.is_file():
            continue
        meta = json.loads(meta_file.read_text(encoding="utf-8"))
        pid = meta.pop("id")
        meta = {k: v for k, v in meta.items() if v is not None}
        meta["license"] = LICENSE
        enrich(meta)                       # property classes, DIN equivalents, synonyms, bearing designations
        if "designation" not in meta.get("properties", {}):
            meta = with_designation(meta)
        out.append(Item(id=pid, file=step, url=None, meta=meta))
    return out


def revision(src: Path) -> str:
    try:
        from importlib.metadata import version
        return f"bd_warehouse {version('bd_warehouse')}"
    except Exception:  # noqa: BLE001 - built in another environment than the generator
        return "bd_warehouse 0.4.0"


